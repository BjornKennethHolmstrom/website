/** @param {string} lang */
function normalize(lang) {
	const s = String(lang || 'en').toLowerCase().replace('-', '_');
	if (s in TEXT) return s;
	const base = s.split('_')[0];
	if (base === 'pt') return 'pt_br';
	return base in TEXT ? base : 'en';
}

/**
 * @param {string} [lang] e.g. 'en', 'sv', 'pt_br', 'pt-BR'
 * @param {'ai' | 'human'} [kind] 'human' for texts you wrote yourself
 * @returns {{ lang: string, dir: 'ltr' | 'rtl', byline: string, note: string | null, more: string, paper: string | null, citeSuffix: string }}
 */
export function getProvenance(lang = 'en', kind = 'ai') {
	const key = normalize(lang);
	const t = TEXT[key];
	return {
		lang: key === 'pt_br' ? 'pt-BR' : key,
		dir: RTL.has(key) ? 'rtl' : 'ltr',
		byline: kind === 'human' ? t.human : t.byline,
		note: kind === 'human' ? null : t.note.replaceAll('{models}', MODELS),
		more: t.more,
		// Working papers only (English and Swedish)
		paper: kind === 'human' ? null : (t.paper ?? TEXT.en.paper),
		citeSuffix: t.citeSuffix ?? TEXT.en.citeSuffix
	};
}
